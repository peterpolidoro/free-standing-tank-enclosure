class Misfit(ValueError):
    """The numbers of the study do not give parts that fit; the message says which limit and by how much."""


def dumps(value, depth=0):
    """JSON as a person would lay it out: a vector, a matrix or a short record on one line, the rest indented."""
    pad = "  " * depth

    def plain(v):
        return not isinstance(v, (dict, list))

    def flat(v):
        return isinstance(v, list) and all(plain(x) for x in v)
    if isinstance(value, dict):
        if not value:
            return "{}"
        if all(plain(v) or flat(v) for v in value.values()):
            line = "{" + ", ".join(f"{json.dumps(k)}: {dumps(v)}" for k, v in value.items()) + "}"
            if depth and len(pad) + len(line) <= 200:
                return line
        return "{\n" + ",\n".join(f"{pad}  {json.dumps(k)}: {dumps(v, depth + 1)}" for k, v in value.items()) + "\n" + pad + "}"
    if isinstance(value, list):
        if flat(value) or all(flat(v) for v in value):
            return "[" + ", ".join(dumps(v) for v in value) + "]"
        return "[\n" + ",\n".join(pad + "  " + dumps(v, depth + 1) for v in value) + "\n" + pad + "]"
    return json.dumps(value, ensure_ascii=False)


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    text = dumps(data) + "\n"
    if json.loads(text) != data:
        raise SystemExit(f"{path}: what would be written does not read back as what was meant")
    path.write_text(text, encoding="utf-8")


def r4(value):
    """A length to a tenth of a micron, as a number that prints short."""
    return round(value, 4) + 0.0


def change(study, assignment):
    """Apply NAME=VALUE to a study. NAME is a dotted place, or a last word that occurs once."""
    name, sep, text = assignment.partition("=")
    if not sep:
        raise SystemExit(f"{assignment!r}: expected NAME=VALUE")
    try:
        value = json.loads(text)
    except json.JSONDecodeError:
        value = text
    places = []

    def walk(node, path):
        for key, child in node.items():
            if isinstance(child, dict):
                walk(child, path + [key])
            elif key != "note":
                places.append(path + [key])
    walk({k: v for k, v in study.items() if k != "what_the_numbers_mean"}, [])
    wanted = name.split(".")
    found = [p for p in places if p == wanted] or [p for p in places if len(wanted) == 1 and p[-1] == name]
    if len(found) != 1:
        some = ", ".join(".".join(p) for p in (found or places))
        raise SystemExit(f"{name!r} names {'no' if not found else 'more than one'} number of the study; there are: {some}")
    node = study
    for key in found[0][:-1]:
        node = node[key]
    node[found[0][-1]] = value
    return ".".join(found[0])


