"""Write what follows from the bowl study: the parameters, checks and interfaces of its parts, and the assembly.

    python3 studies/bowls/derive.py                           this project's files, from study.json
    python3 studies/bowls/derive.py --show NAME=VALUE ...     what would follow from other values; nothing is written
    python3 studies/bowls/derive.py --options                 which bowls fit a monitor: options.md, and printed
    python3 studies/bowls/derive.py --out DIR NAME=VALUE ...  a variant: the bowl parts as a project of their own in
                                                              DIR (which must not exist), with those values changed
    python3 studies/bowls/derive.py --subjects [STUDY.json]   the names of the frame and the bowls in the assembly,
                                                              for a fit check; of this study, or of a variant's
    python3 studies/bowls/derive.py --row                     the plane through the first row of bowls, as CUT= takes it

study.json is the one file of numbers: the bowl as asked for and as assumed, how many stand over a monitor, the
frame, the sheet and the plug. A NAME is a number's place in it, `bowl.asked.opening_diameter`, or its last word
where that is the only one of that name, `opening_diameter`.

The layout gives every part its own parameters.json, its own checks.json with numbers in it, and the assembly its
own placements. So that one changed number reaches all of them, this script is the one writer of

    designs/parts/{bowl,bowl-forming-plug,bowl-frame,display-cover-sheet}/parameters.json
    designs/parts/{bowl,bowl-forming-plug,bowl-frame,display-cover-sheet}/checks.json
    designs/parts/{bowl,bowl-frame}/interface.json
    designs/assemblies/monitor-with-bowls/assembly.json
    studies/bowls/summary.md        the numbers as they stand
    studies/bowls/questions.md      a page for the researcher: what is drawn, what fits, what has to be known
    studies/bowls/options.md        (--options) which sizes fit

and the programs (build.py) and the README files are written by hand. Building is then the layout's own command,
part by part; `make bowls` in this project does both.

Nothing here needs a CAD kernel, so a question such as "do six bowls of 150 mm fit?" is answered at once. The
checks it writes name points of a part that must be material or empty; where the surfaces are is worked out here
from the study's numbers, a second way beside the programs that build the solids, so a check that a built solid
fails is a disagreement between the two. The monitor is not written here: its lit area and its outline are read
from designs/parts/aw2725q-monitor/interface.json.

Standard library only.
"""
