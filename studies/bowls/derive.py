        f"{counts} bowls over a lit area of {2 * display['half'][0]:.2f} × {2 * display['half'][1]:.2f} mm, spaced as evenly as",
        f"the limits allow: every opening at least {study['limits']['opening_inside_display']:g} mm inside the lit area, at least",
        f"{study['limits']['least_gap_between_flanges']:g} mm between two flanges, and at least {study['limits']['least_web']:g} mm of frame between two",
        "holes and between a hole and the plate's edge. Everything else as in the study: a wall of "
        f"{study['bowl']['assumed']['wall_thickness']:g} mm, {study['bowl']['assumed']['wall_draft_deg']:g}° of draft, a frame of "
