    webs = []
    if found["columns"] > 1:
        webs.append(("web-between-two-columns", ((seats[0][0] + seats[1][0]) / 2, seats[0][1], z)))
    if found["rows"] > 1:
        mid = found["columns"] // 2
        above = seats[found["columns"] + mid]
        webs.append(("web-between-two-rows", (seats[mid][0], (seats[mid][1] + above[1]) / 2, z)))
    for pid, xyz in webs:
        checks.append(point(pid, xyz, "material"))
    solid_at = webs[0][1] if webs else (plate["max"][0] - frame["corner_radius"] - 1, plate["min"][1] + frame["corner_radius"] + 1, z)
