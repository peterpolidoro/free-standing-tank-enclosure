def work_out(study, project):
    """Everything that follows from a study, as a dictionary; a Misfit when its parts do not fit."""
    bowl = Bowl(study)
    mon = monitor(project)
    found = layout(study, bowl, mon)
    b_par, b_checks, b_iface = None, None, None
    profile = program(project, "bowl")["profile"]
    corners, radii = profile({"requested_mm": {"inside_diameter_at_rim": 2 * bowl.R, "inside_depth": bowl.D},
                              "assumed_mm": study["bowl"]["assumed"]})
    outline = rounded(corners, radii)
    volume = turned(outline)
    inside = [p for p in rounded(corners[:4] + [(corners[3][0], bowl.height), (0.0, bowl.height)], {1: radii[1], 2: radii[2]})
              if p[0] <= bowl.rim_tangent + 1e-9]
    cavity = turned(inside)
    b_par, b_checks, b_iface = bowl_files(study, bowl, volume)
    s_par, s_checks = sheet_files(study, mon, found["plate"])
    f_par, f_checks, f_iface = frame_files(study, bowl, found)
    p_par, p_checks, plug = plug_files(study, bowl, cavity, program(project, "bowl-forming-plug")["plan"])
    return {
        "bowl": bowl, "monitor": mon, "layout": found, "volume": volume, "cavity": cavity, "plug": plug,
        "files": {
            "designs/parts/bowl/parameters.json": b_par, "designs/parts/bowl/checks.json": b_checks,
            "designs/parts/bowl/interface.json": b_iface,
            "designs/parts/display-cover-sheet/parameters.json": s_par, "designs/parts/display-cover-sheet/checks.json": s_checks,
            "designs/parts/bowl-frame/parameters.json": f_par, "designs/parts/bowl-frame/checks.json": f_checks,
            "designs/parts/bowl-frame/interface.json": f_iface,
            "designs/parts/bowl-forming-plug/parameters.json": p_par, "designs/parts/bowl-forming-plug/checks.json": p_checks,
            f"designs/assemblies/{ASSEMBLY}/assembly.json": assembly_file(study, found),
        }}


