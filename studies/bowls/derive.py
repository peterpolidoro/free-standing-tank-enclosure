def monitor(project):
    """The lit area and the body's outline, from the monitor's interface: centre and half extent of each."""
    data = json.loads((project / "designs" / "parts" / MONITOR / "interface.json").read_text(encoding="utf-8"))
    out = {}
    for fid in ("active-display", "body"):
        f = next(x for x in data["features"] if x["id"] == fid)
        if f["normal"] != [0.0, 0.0, 1.0] or f["x"] != [1.0, 0.0, 0.0]:
            raise SystemExit(f"{MONITOR}: {fid} is expected in the front, with x to the right")
        xs, ys = [p[0] for p in f["polygon"]], [p[1] for p in f["polygon"]]
        out[fid] = {"centre": (f["point"][0] + (max(xs) + min(xs)) / 2, f["point"][1] + (max(ys) + min(ys)) / 2),
                    "half": ((max(xs) - min(xs)) / 2, (max(ys) - min(ys)) / 2), "z": f["point"][2]}
    return out


def layout(study, bowl, mon):
    """Where the bowls stand over the display and what is left round them; a Misfit when they do not fit."""
    arrangement, limits, frame, sheet = study["layout"], study["limits"], study["frame"], study["sheet"]
    counts = (arrangement["columns"], arrangement["rows"])
    if not all(isinstance(n, int) and n >= 1 for n in counts):
        raise Misfit("columns and rows are whole numbers, one or more")
    thickness = frame["thickness"]
    if not 0 < thickness < bowl.D:
        raise Misfit(f"the frame, {thickness} mm, has to be thinner than the bowl is deep under its flange, {bowl.D} mm")
    hole = bowl.outside(thickness) + frame["radial_clearance"]
    display, body = mon["active-display"], mon["body"]
    plate = {"min": [r4(body["centre"][k] - body["half"][k] - sheet["overhang"]) for k in (0, 1)],
             "max": [r4(body["centre"][k] + body["half"][k] + sheet["overhang"]) for k in (0, 1)]}
    pitch, how, wrong = [0.0, 0.0], ["one", "one"], []
    for k, axis in ((0, "x"), (1, "y")):
        n, given = counts[k], arrangement["pitch_" + axis]
        if n == 1:
            continue
        least = max(2 * bowl.flange_radius + limits["least_gap_between_flanges"], 2 * hole + limits["least_web"])
        most = (2 * display["half"][k] - 2 * bowl.R - 2 * limits["opening_inside_display"]) / (n - 1)
        if given == "auto":
            if least > most:
                wrong.append(f"along {axis}, {n} bowls need a pitch of at least {least:.2f} mm and the lit area "
                             f"allows {most:.2f} mm: short by {(least - most) * (n - 1):.2f} mm in all")
                pitch[k], how[k] = least, "auto"
                continue
            even = 2 * display["half"][k] / n
            pitch[k] = round(even if least <= even <= most else (least + most) / 2, 2)
            pitch[k] = min(max(pitch[k], math.ceil(least * 100) / 100), math.floor(most * 100) / 100)
            how[k] = "auto: even" if least <= even <= most else "auto: between its two limits"
        else:
            pitch[k], how[k] = float(given), "given"
    centre = display["centre"]
    seats = [(r4(centre[0] + (i - (counts[0] - 1) / 2) * pitch[0]), r4(centre[1] + (j - (counts[1] - 1) / 2) * pitch[1]))
             for j in range(counts[1]) for i in range(counts[0])]
    spans = [(counts[k] - 1) * pitch[k] / 2 for k in (0, 1)]
    several = [k for k in (0, 1) if counts[k] > 1]
    edges = {"left": min(x for x, _ in seats) - hole - plate["min"][0], "right": plate["max"][0] - max(x for x, _ in seats) - hole,
             "lower": min(y for _, y in seats) - hole - plate["min"][1], "upper": plate["max"][1] - max(y for _, y in seats) - hole}
    found = {
        "columns": counts[0], "rows": counts[1], "pitch": pitch, "how": how, "seats": seats, "plate": plate,
        "hole_diameter": 2 * hole, "bowl_diameter_at_upper_face": 2 * bowl.outside(thickness),
        "opening_inside_display": [display["half"][k] - spans[k] - bowl.R for k in (0, 1)],
        "web_between_holes": [pitch[k] - 2 * hole if k in several else None for k in (0, 1)],
        "gap_between_flanges": [pitch[k] - 2 * bowl.flange_radius if k in several else None for k in (0, 1)],
        "web_to_edge": edges,
        "flange_inside_plate": min(min(x for x, _ in seats) - bowl.flange_radius - plate["min"][0],
                                   plate["max"][0] - max(x for x, _ in seats) - bowl.flange_radius,
                                   min(y for _, y in seats) - bowl.flange_radius - plate["min"][1],
                                   plate["max"][1] - max(y for _, y in seats) - bowl.flange_radius),
    }
    if not wrong:
        for k, axis in ((0, "x"), (1, "y")):
            inside = found["opening_inside_display"][k]
            if inside < limits["opening_inside_display"] - 1e-9:
                wrong.append(f"along {axis} the openings reach {limits['opening_inside_display'] - inside:.2f} mm "
                             "further out of the lit area than allowed")
            if k in several and found["web_between_holes"][k] < limits["least_web"] - 1e-9:
                wrong.append(f"along {axis} {found['web_between_holes'][k]:.2f} mm of frame is left between two holes, "
                             f"less than {limits['least_web']} mm")
            if k in several and found["gap_between_flanges"][k] < limits["least_gap_between_flanges"] - 1e-9:
                wrong.append(f"along {axis} two flanges are {found['gap_between_flanges'][k]:.2f} mm apart, "
                             f"less than {limits['least_gap_between_flanges']} mm")
        for name, web in edges.items():
            if web < limits["least_web"] - 1e-9:
                wrong.append(f"{web:.2f} mm of frame is left between a hole and the {name} edge, "
                             f"less than {limits['least_web']} mm")
    if wrong:
        raise Misfit("; ".join(wrong))
    return found


