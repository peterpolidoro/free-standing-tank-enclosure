def derive(project, study, show=False):
    got = work_out(study, project)
    text = summary(study, got)
    if show:
        print(text)
        return got
    for name, data in got["files"].items():
        write_json(project / name, data)
    (project / "studies" / "bowls").mkdir(parents=True, exist_ok=True)
    (project / "studies" / "bowls" / "summary.md").write_text(text, encoding="utf-8")
    (project / "studies" / "bowls" / "questions.md").write_text(questions(study, got, project), encoding="utf-8")
    found, bowl = got["layout"], got["bowl"]
    print(f"[derive] {project}: a bowl of {2 * bowl.R:g} mm, {found['columns']} x {found['rows']} at "
          f"{found['pitch'][0]:.2f} x {found['pitch'][1]:.2f} mm; openings {min(found['opening_inside_display']):.2f} mm "
          f"inside the lit area at the least; holes of {found['hole_diameter']:.2f} mm")
    print(f"[derive] wrote {len(got['files'])} files under designs/, and summary.md and questions.md in studies/bowls/; "
          "build with: make bowls")
    return got


def variant(out, study):
    out = Path(out)
    if out.exists():
        raise SystemExit(f"{out} exists; a variant is written into a new directory")
    work_out(study, PROJECT)                      # refuse before anything is written
    for key in PARTS:
        target = out / "designs" / "parts" / key
        target.mkdir(parents=True)
        for name in ("build.py", "README.md"):
            shutil.copy2(PROJECT / "designs" / "parts" / key / name, target / name)
    shutil.copytree(PROJECT / "designs" / "parts" / MONITOR, out / "designs" / "parts" / MONITOR)
    (out / "designs" / "assemblies" / ASSEMBLY).mkdir(parents=True)
    shutil.copy2(PROJECT / "designs" / "assemblies" / ASSEMBLY / "README.md", out / "designs" / "assemblies" / ASSEMBLY / "README.md")
    write_json(out / "studies" / "bowls" / "study.json", study)
    derive(out, study)


def main(argv):
    study = json.loads((HERE / "study.json").read_text(encoding="utf-8"))
    mode, out = "write", None
    if argv[:1] == ["--show"]:
        mode, argv = "show", argv[1:]
    elif argv[:1] == ["--options"]:
        mode, argv = "options", argv[1:]
    elif argv[:1] == ["--out"] and len(argv) >= 2:
        mode, out, argv = "variant", argv[1], argv[2:]
    elif argv[:1] == ["--row"]:
        # the plane through the axes of the first row of bowls, as `make section` and `make picture` take it
        print(f"-y={work_out(study, PROJECT)['layout']['seats'][0][1]:g}")
        return 0
    elif argv[:1] == ["--subjects"]:
        if len(argv) > 1:
            study = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
        count = study["layout"]["columns"] * study["layout"]["rows"]
        print(",".join(["BOWL FRAME:1"] + [f"BOWL:{n}" for n in range(1, count + 1)]))
        return 0
    elif argv and argv[0].startswith("--"):
        raise SystemExit(__doc__)
    changed = [change(study, a) for a in argv]
    if mode == "write" and changed:
        raise SystemExit("values are changed in study.json, or tried with --show or --out; nothing was written")
    try:
        if mode == "options":
            text = options(study, PROJECT)
            if not changed:
                (HERE / "options.md").write_text(text, encoding="utf-8")
            print(text)
        elif mode == "variant":
            variant(out, study)
        else:
            derive(PROJECT, study, show=(mode == "show"))
    except Misfit as exc:
        print(f"[derive] DOES NOT FIT: {exc}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
