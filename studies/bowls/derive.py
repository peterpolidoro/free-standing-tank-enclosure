class Bowl:
    """The bowl's section from the study's numbers: where its two surfaces are at a height above its underside.

    The inside runs flat floor, a radius, a straight wall that leans outwards by the draft, a radius the other
    way at the rim, and the flat flange. The outside is the same one wall thickness further out, its two radii
    about the same centres. Heights are measured from the underside of the floor, as in the part's own frame.
    """

    def __init__(self, study):
        asked, assumed = study["bowl"]["asked"], study["bowl"]["assumed"]
        self.R, self.D = asked["opening_diameter"] / 2, asked["depth"]
        self.t, self.draft = assumed["wall_thickness"], math.radians(assumed["wall_draft_deg"])
        self.rf, self.rr, self.w = assumed["floor_corner_radius"], assumed["rim_radius"], assumed["flange_width"]
        for name, value in (("opening_diameter", self.R), ("depth", self.D), ("wall_thickness", self.t),
                            ("floor_corner_radius", self.rf), ("flange_width", self.w)):
            if not value > 0:
                raise Misfit(f"{name} has to be more than nothing")
        if not 0 <= self.draft < math.radians(60):
            raise Misfit("the wall's draft is between 0 and 60 degrees")
        if self.rr < self.t:
            raise Misfit(f"the rim's radius, {self.rr} mm, cannot be smaller than the wall, {self.t} mm")
        self.turn = math.tan((math.pi / 2 - self.draft) / 2)       # a radius r takes r * turn of each line it joins
        self.floor_corner = self.R - self.D * math.tan(self.draft)  # where the inside of the wall would meet the floor
        self.flat = self.floor_corner - self.rf * self.turn         # the flat floor ends here
        self.rim_tangent = self.R + self.rr * self.turn             # the rim's radius ends here, on the rim's plane
        if self.flat <= 0:
            raise Misfit("the floor's corner radius leaves no flat floor")
        if (self.rf + self.rr) * self.turn > self.D / math.cos(self.draft):
            raise Misfit("the wall is too short for the radius at the floor and the radius at the rim together")
        if self.w <= self.rr * self.turn:
            raise Misfit(f"the flange, {self.w} mm, is narrower than the rim's radius needs "
                         f"({self.rr * self.turn:.2f} mm)")
        self.height, self.flange_radius = self.D + self.t, self.R + self.w
        s = math.sin(self.draft)
        self.straight = (self.t + self.rf * (1 - s),                # the wall is straight on both faces between these
                         self.height - self.rr + (self.rr - self.t) * s)
        if self.straight[1] - self.straight[0] < 4 * OFF:
            raise Misfit("the two radii leave no straight wall to speak of; the checks need one")

    def line(self, z):
        """The inside of the wall at height z, were it straight all the way."""
        return self.R - (self.height - z) * math.tan(self.draft)

    def inside(self, z):
        t, rf, rr = self.t, self.rf, self.rr
        if z <= t + rf * (1 - math.sin(self.draft)):
            return self.flat + math.sqrt(max(rf ** 2 - (t + rf - z) ** 2, 0.0))
        if z <= self.height - rr * (1 - math.sin(self.draft)):
            return self.line(z)
        return self.rim_tangent - math.sqrt(max(rr ** 2 - (z - (self.height - rr)) ** 2, 0.0))

    def outside(self, z):
        """The outside of the bowl at height z, for a height under the flange."""
        t, rf, rr = self.t, self.rf, self.rr
        if z <= t + rf - (rf + t) * math.sin(self.draft):
            return self.flat + math.sqrt(max((rf + t) ** 2 - (t + rf - z) ** 2, 0.0))
        if z <= self.straight[1] or rr <= t:
            return self.line(z) + t / math.cos(self.draft)
        return self.rim_tangent - math.sqrt(max((rr - t) ** 2 - (z - (self.height - rr)) ** 2, 0.0))


def rounded(corners, radii, steps=2000):
    """A closed outline with some of its corners rounded, as a fine polygon."""
    n, out = len(corners), []
    for i, p in enumerate(corners):
        r = radii.get(i, 0)
        if r <= 0:
            out.append(p)
            continue
        a, b = corners[i - 1], corners[(i + 1) % n]
        u1, u2 = (a[0] - p[0], a[1] - p[1]), (b[0] - p[0], b[1] - p[1])
        l1, l2 = math.hypot(*u1), math.hypot(*u2)
        u1, u2 = (u1[0] / l1, u1[1] / l1), (u2[0] / l2, u2[1] / l2)
        theta = math.acos(max(-1.0, min(1.0, u1[0] * u2[0] + u1[1] * u2[1])))
        d = r / math.tan(theta / 2)
        if d > min(l1, l2) + 1e-9:
            raise Misfit("a radius of the bowl's section is larger than the lines it joins")
        bis = (u1[0] + u2[0], u1[1] + u2[1])
        lb = math.hypot(*bis)
        c = (p[0] + bis[0] / lb * r / math.sin(theta / 2), p[1] + bis[1] / lb * r / math.sin(theta / 2))
        t1, t2 = (p[0] + u1[0] * d, p[1] + u1[1] * d), (p[0] + u2[0] * d, p[1] + u2[1] * d)
        a1, a2 = math.atan2(t1[1] - c[1], t1[0] - c[0]), math.atan2(t2[1] - c[1], t2[0] - c[0])
        da = (a2 - a1 + math.pi) % (2 * math.pi) - math.pi
        out.extend((c[0] + r * math.cos(a1 + da * k / steps), c[1] + r * math.sin(a1 + da * k / steps))
                   for k in range(steps + 1))
    return out


def turned(outline):
    """The volume of an outline in the plane through an axis, turned about that axis (x is the radius)."""
    moment = 0.0
    for (x0, y0), (x1, y1) in zip(outline, outline[1:] + outline[:1]):
        moment += (x0 + x1) * (x0 * y1 - x1 * y0) / 6
    return 2 * math.pi * abs(moment)


def program(project, key):
    """What a part's build.py defines, without building anything: its helpers are plain Python."""
    path = project / "designs" / "parts" / key / "build.py"
    namespace = {"__file__": str(path), "__name__": "derive_" + key.replace("-", "_")}
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), namespace)
    return namespace


