"""Generate the MkDocs pages of the project site from the published manual package.

Reads docs/manual/manual.json (with its hotspots and, when present, the viewer data
and the exploded view) and the committed scene for subassembly instance counts, and
writes docs/index.md, docs/subassemblies/<slug>.md, docs/parts.md, docs/joints.md,
docs/supplement.md and docs/record.md. The front page shows the whole assembly with
numbered callouts that link to one page per subassembly definition; with the viewer
data (docs/manual/viewer/) it becomes a <model-viewer> model that turns, with the
same numbered hotspots, an SVG fallback without WebGL and a plain picture on the forge,
as on the mouse-joystick-pcb site. Pure derivation: re-running rewrites the same
files; nothing under docs/manual/ is written. The prose of the front page comes from
assembly/site/index.md.in.
"""
from __future__ import annotations

import argparse
import hashlib
import html
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
MANUAL = DOCS / "manual"
SCENE = ROOT / "references" / "enclosure" / "scene.json"
TEMPLATE = ROOT / "assembly" / "site" / "index.md.in"
MARK = "<!-- Generated by assembly/site_pages.py from docs/manual/manual.json; do not edit. -->"
MODEL_VIEWER = "https://ajax.googleapis.com/ajax/libs/model-viewer/4.0.0/model-viewer.min.js"
E = html.escape


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def short_hash(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()[:12]


def union(boxes):
    if not boxes:
        return None
    return [min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes)]


class Site:
    def __init__(self, manual_dir=MANUAL, scene_path=SCENE):
        self.manual_dir = Path(manual_dir)
        self.m = read_json(self.manual_dir / "manual.json")
        self.scene = read_json(scene_path) if Path(scene_path).exists() else None
        self.source = read_json(self.manual_dir / "SOURCE.json") if (self.manual_dir / "SOURCE.json").exists() else {}
        self.parts_by_id = {p["part_id"]: p for p in self.m["inventory"]}
        self.hot = {k: read_json(self.manual_dir / v) for k, v in self.m.get("hotspots", {}).items()
                    if (self.manual_dir / v).exists()}
        viewer = self.m.get("viewer", {}).get("hotspots") or "viewer/hotspots.json"
        self.viewer = read_json(self.manual_dir / viewer) if (self.manual_dir / viewer).exists() else None
        self.units = self.definitions()

    # ---- subassembly definitions and their instances -------------------------------------
    def scene_assemblies(self):
        return {a["id"]: a for a in (self.scene or {}).get("assemblies", [])}

    def definition_of(self, assembly_id):
        a = self.scene_assemblies().get(assembly_id)
        if a and a.get("document"):
            return Path(a["document"].replace("\\", "/")).stem
        return re.sub(r":\d+$", "", assembly_id.split("/")[-1])

    def occurrences_under(self, assembly_id):
        prefix = assembly_id + "/"
        return [o for o in (self.scene or {}).get("occurrences", []) if o["id"].startswith(prefix)]

    def signature(self, assembly_id):
        occs = self.occurrences_under(assembly_id)
        if any(o.get("suppressed") for o in occs):
            return None
        return tuple(sorted(Counter(o["part_id"] for o in occs).items()))

    def definitions(self):
        units = []
        for g in self.m["groups"]:
            definition = g.get("definition") or self.definition_of(g["id"])
            instance_ids = g.get("instance_ids")
            if not instance_ids:
                instance_ids = sorted(aid for aid in self.scene_assemblies() if self.definition_of(aid) == definition) or [g["id"]]
            identical = g.get("instances_identical")
            if identical is None and self.scene:
                sigs = {self.signature(i) for i in instance_ids}
                identical = len(sigs) == 1 and None not in sigs
            if len(instance_ids) == 1:
                identical = True   # a single instance has nothing to differ from
            units.append({
                "number": g["index"], "definition": definition, "slug": slug(definition), "group": g,
                "shown": g["id"], "instance_ids": instance_ids, "count": len(instance_ids),
                "identical": identical, "kind": "subassembly",
            })
        root_occ = [o for o in (self.scene or {}).get("occurrences", []) if o.get("parent_id") == "root"]
        if not root_occ:
            root_occ = [{"id": o, "part_id": p["part_id"]} for p in self.m["inventory"] for o in p.get("occurrences", []) if "/" not in o]
        units.append({
            "number": len(self.m["groups"]) + 1, "definition": "Root-level parts", "slug": "root-level-parts",
            "group": None, "shown": "root", "instance_ids": ["root"], "count": 1, "identical": True,
            "kind": "root", "occurrences": root_occ,
        })
        return units

    def unit_box(self, unit, view="overview"):
        hs = self.hot.get(view)
        if not hs:
            return None
        if unit["kind"] == "root":
            ids = {o["id"] for o in unit["occurrences"]}
            boxes = [o["box_px"] for o in hs["occurrences"] if o["id"] in ids]
        else:
            prefix = unit["shown"] + "/"
            boxes = [o["box_px"] for o in hs["occurrences"] if o["id"].startswith(prefix)]
        return union(boxes)

    def unit_parts(self, unit):
        """Rows (label, part, qty per instance) of a unit."""
        if unit["kind"] == "root":
            c = Counter(o["part_id"] for o in unit["occurrences"])
        else:
            c = Counter((p["part_id"], p["qty"]) for p in unit["group"]["parts"])
            c = {pid: q for (pid, q) in c}
        rows = []
        for pid, qty in c.items():
            part = self.parts_by_id.get(pid)
            if part:
                rows.append((part, qty))
        return sorted(rows, key=lambda r: r[0]["label"])

    def unit_joints(self, unit):
        ctx = set(unit["instance_ids"]) if unit["kind"] != "root" else {"root"}
        return [j for j in self.m["joints"] if j.get("context_assembly") in ctx]

    def unit_hardware(self, unit):
        if unit["kind"] == "root":
            seen, out = set(), []
            for j in self.unit_joints(unit):
                for h in j.get("hardware", []):
                    if h["item_id"] not in seen:
                        seen.add(h["item_id"])
                        out.append(h)
            return out
        return unit["group"].get("hardware", [])

    # ---- HTML fragments --------------------------------------------------------------------
    def callout_svg(self, view, targets, base, link_for):
        """SVG overlay (web only) with one numbered callout per target: (number, box, title)."""
        hs = self.hot.get(view)
        if not hs:
            return ""
        w, h = hs["width"], hs["height"]
        o = [f'<svg class="callouts" viewBox="0 0 {w} {h}" aria-label="Numbered callouts; each number is a link">']
        for number, box, title in sorted(targets, key=lambda t: -((t[1][2] - t[1][0]) * (t[1][3] - t[1][1]))):
            x0, y0, x1, y1 = box
            cx, cy = x0 + 26, y0 + 26
            o.append(f'<a href="{E(link_for(number))}"><title>{E(title)}</title>'
                     f'<rect x="{x0:.0f}" y="{y0:.0f}" width="{x1 - x0:.0f}" height="{y1 - y0:.0f}"/>'
                     f'<circle cx="{cx:.0f}" cy="{cy:.0f}" r="26"/><text x="{cx:.0f}" y="{cy:.0f}">{number}</text></a>')
        o.append("</svg>")
        return "\n".join(o)

    def figure_with_callouts(self, image, view, targets, base, link_for, caption):
        svg = self.callout_svg(view, targets, base, link_for)
        return (f'<figure class="ov"><div class="ov-wrap"><img src="{base}manual/images/{E(image)}" alt="{E(caption)}">'
                f'{svg}</div><figcaption>{E(caption)} The numbers are links.</figcaption></figure>')

    def unit_targets(self, view):
        targets = []
        for u in self.units:
            box = self.unit_box(u, view)
            if box:
                targets.append((u["number"], box, f"{u['number']}: {u['definition']} ({u['count']} in the project)"))
        return targets

    def viewer_block(self, base=""):
        v = self.viewer
        if not v:
            return None
        by_number = {u["number"]: u for u in self.units}
        states = {}
        for name, st in v["states"].items():
            glb = self.manual_dir / st["glb"]
            if not glb.exists():
                return None
            states[name] = {"src": f"{base}manual/{st['glb']}?v={short_hash(glb)}", "hotspots": {}}
        entries = list(v.get("subassemblies", [])) + ([v["root_parts"]] if v.get("root_parts") else [])
        hot_html = []
        for s in entries:
            u = by_number.get(s["number"])
            if not u:
                continue
            for name in states:
                a = s["anchors"][name]
                states[name]["hotspots"][str(s["number"])] = {"p": " ".join(f"{c:.5f}" for c in a["position_m"]),
                                                               "nrm": " ".join(f"{c:.3f}" for c in a["normal"])}
            a = s["anchors"]["assembled"]
            hot_html.append(
                f'<a class="hotspot" slot="hotspot-{s["number"]}" data-position="{" ".join(f"{c:.5f}" for c in a["position_m"])}" '
                f'data-normal="{" ".join(f"{c:.3f}" for c in a["normal"])}" data-n="{s["number"]}" '
                f'href="{base}subassemblies/{u["slug"]}/" title="{E(u["definition"])}" '
                f'aria-label="{s["number"]}: {E(u["definition"])}"></a>')
        toggle = ('<button type="button" id="asm-toggle" class="md-button">Show exploded</button>' if "exploded" in states else "")
        return f"""<script type="module" src="{MODEL_VIEWER}"></script>
<script>
(function(){{try{{var c=document.createElement('canvas');if('customElements' in window&&(c.getContext('webgl2')||c.getContext('webgl')))document.documentElement.classList.add('webgl');}}catch(e){{}}}})();
</script>
<div class="asm-3d">
<model-viewer id="assembly" src="{states['assembled']['src']}" alt="The enclosure" camera-controls touch-action="pan-y"
 camera-orbit="35deg 70deg auto" field-of-view="30deg" shadow-intensity="0.5" exposure="0.8" interaction-prompt="none"
 style="width:100%;height:560px;background:#fff;border-radius:8px">
{chr(10).join(hot_html)}
</model-viewer>
<p class="asm-hint">Drag to turn, scroll to zoom; the numbers are links. {toggle}</p>
<script>
(function(){{var mv=document.getElementById('assembly');if(!mv)return;
var states={json.dumps(states)};var state='assembled';var btn=document.getElementById('asm-toggle');
if(btn)btn.addEventListener('click',function(){{state=state==='assembled'?'exploded':'assembled';mv.setAttribute('src',states[state].src);
var hs=states[state].hotspots;mv.querySelectorAll('a.hotspot').forEach(function(a){{var h=hs[a.dataset.n];if(h){{a.dataset.position=h.p;a.dataset.normal=h.nrm;}}}});
btn.textContent=state==='assembled'?'Show exploded':'Show assembled';}});
var fallback=function(){{document.documentElement.classList.remove('webgl');}};
mv.addEventListener('error',fallback);var t=setTimeout(fallback,20000);
if(window.customElements)customElements.whenDefined('model-viewer').then(function(){{clearTimeout(t);}});}})();
</script>
</div>
<div class="asm-2d">"""

    def front_view(self, base=""):
        link = lambda n: f"{base}subassemblies/{ {u['number']: u['slug'] for u in self.units}[n] }/"
        fig = self.figure_with_callouts(self.m["overview_image"], "overview", self.unit_targets("overview"), base, link,
                                        "The finished assembly, all parts at their CAD positions.")
        exploded = ""
        ev = self.m.get("exploded_view")
        if ev and (self.manual_dir / "images" / ev["image"]).exists():
            targets = [(c["number"], c["box_px"], f"{c['number']}: {c['definition']}") for c in ev.get("callouts", [])]
            view = "exploded" if "exploded" in self.hot else None
            if view:
                exploded = self.figure_with_callouts(ev["image"], view, targets, base, link,
                                                     "Exploded view: each subassembly moved as a rigid body; illustration only, not an assembly order.")
            else:
                exploded = f'<figure class="ov"><img src="{base}manual/images/{E(ev["image"])}" alt="Exploded view"><figcaption>Exploded view (illustration only).</figcaption></figure>'
        viewer = self.viewer_block(base)
        if viewer:
            return (viewer + "\n" + fig + exploded + "\n</div>\n"
                    f'<div class="asm-plain" markdown>\n\n![The finished assembly]({base}manual/images/{self.m["overview_image"]})\n\n</div>\n')
        return fig + exploded

    def key_table(self):
        rows = ["| # | Subassembly | In the project | Parts in one | Page |", "| ---: | --- | ---: | ---: | --- |"]
        for u in self.units:
            n_parts = sum(q for _, q in self.unit_parts(u))
            ident = "" if u["identical"] in (True, None) else " (instances differ)"
            rows.append(f"| {u['number']} | {u['definition']} | {u['count']}{ident} | {n_parts} | [{u['slug']}](subassemblies/{u['slug']}.md) |")
        return "\n".join(rows)

    # ---- pages ----------------------------------------------------------------------------
    def status_block(self, full=True, base=""):
        """The manual's status lines (they already include the project notes); on the inner
        pages a one-line reminder that links to the full block on the front page."""
        if not full:
            return (f'!!! warning "{E(self.m["review_state"].capitalize())} documentation"\n\n'
                    f"    Inspection views and CAD instance counts, not assembly steps, stock or a purchase list; "
                    f"the full status is on the [front page]({base}index.md) and the [build record]({base}record.md).\n")
        lines = [f'!!! warning "{E(self.m["review_state"].capitalize())} documentation"', ""]
        for s in self.m["status_lines"]:
            lines.append(f"    {s}")
            lines.append("")
        return "\n".join(lines)

    def index_page(self):
        t = TEMPLATE.read_text(encoding="utf-8")
        pdfs = sorted(p.name for p in self.manual_dir.glob("*.pdf"))
        pdf_links = " · ".join(f"[{'appendix' if 'appendix' in n else 'compact'} PDF](manual/{n})" for n in pdfs)
        return (t.replace("{{MARK}}", MARK).replace("{{STATUS}}", self.status_block())
                .replace("{{VIEW}}", self.front_view("")).replace("{{KEY}}", self.key_table())
                .replace("{{PDFS}}", pdf_links).replace("{{TITLE}}", self.m["scene"]["title"]))

    def unit_page(self, u):
        base = "../../"
        o = [MARK, f"# Subassembly {u['number']}: {u['definition']}", ""]
        if u["kind"] == "root":
            o.append("Parts placed directly in the root assembly, outside every subassembly.")
        else:
            ids = ", ".join(f"`{i}`" for i in u["instance_ids"])
            plural = "copies" if u["count"] != 1 else "copy"
            o.append(f"**{u['count']} {plural} in the project**: {ids}. The picture shows `{u['shown']}`"
                     + (f" under `{u['group']['parent_id']}`" if u["group"]["parent_id"] not in (None, "root") else "") + ".")
            if u["identical"] is False:
                o.append("")
                o.append("The instances differ in content (flexible, suppressed or overridden occurrences); the totals below are per instance only.")
            elif u["identical"] is None:
                o.append("")
                o.append("Whether the instances are identical has not been checked; the totals assume they are.")
        o.append("")
        o.append(self.status_block(full=False, base="../"))
        o.append("")
        if u["kind"] != "root":
            g = u["group"]
            hs_targets = []
            hs = self.hot.get(g["view_id"])
            if hs:
                for occ in hs["occurrences"]:
                    part = self.parts_by_id.get(occ["part_id"])
                    if part:
                        hs_targets.append((part["label"], occ["box_px"], f"{part['label']}: {part['label_text']}"))
            o.append(self.figure_with_callouts(g["image"], g["view_id"], hs_targets, base, lambda n: f"{base}parts/#part-{n}",
                                               f"{u['definition']}: {g['note']}."))
        else:
            o.append(self.figure_with_callouts(self.m["overview_image"], "overview",
                                               [(self.parts_by_id[oc["part_id"]]["label"], hs["box_px"], self.parts_by_id[oc["part_id"]]["label_text"])
                                                for oc in u["occurrences"] for hs in self.hot.get("overview", {}).get("occurrences", [])
                                                if hs["id"] == oc["id"] and oc["part_id"] in self.parts_by_id],
                                               base, lambda n: f"{base}parts/#part-{n}", "Root-level parts on the finished assembly."))
        o.append("")
        o.append("## Parts")
        o.append("")
        total_h = f"For all {u['count']}" if u["count"] > 1 else "Total"
        o.append(f"| # | Picture | Part | Per subassembly | {total_h} |")
        o.append("| ---: | --- | --- | ---: | ---: |")
        for part, qty in self.unit_parts(u):
            tot = qty * u["count"] if u["identical"] is not False else "—"
            o.append(f"| {part['label']} | <img src=\"{base}manual/images/{E(part['thumbnail'])}\" width=\"72\" alt=\"\"> | "
                     f"[{E(part['label_text'])}](../parts.md#part-{part['label']})<br><small>{E(part['dimensions'])}</small> | {qty} | {tot} |")
        o.append("")
        o.append("CAD quantities are instance counts in the model, not stock and not a purchase list.")
        hw = self.unit_hardware(u)
        if hw:
            o.append("")
            o.append("## Hardware to review at this subassembly (not an approved BOM)")
            o.append("")
            for h in hw:
                o.append(f"- **{h['label']}** {E(h['title'])}: {E(h['status_text'])}; {E(h['required_text'])}; joint `{h['joint_id']}` ([supplementary items](../supplement.md#{slug(h['item_id'])}))")
        joints = self.unit_joints(u)
        if joints:
            o.append("")
            o.append("## Joint close-ups")
            o.append("")
            for j in joints:
                o.append(f"### Joint {j['index']}: {j['joint_id']}")
                o.append("")
                o.append(f"![Joint {j['index']}: {j['joint_id']}](../manual/images/{j['image']})")
                o.append("")
                parts = ", ".join(f"{p['label']} {E(p['label_text'])} ×{p['qty']}" for p in j["parts"])
                o.append(f"Occurrences at their CAD poses; context {E(j['context_short'] or j['context_assembly'])}. Parts: {parts}.")
                for h in j.get("hardware", []):
                    o.append(f"- **{h['label']}** {E(h['title'])}: {E(h['required_text'])}")
                o.append("")
        o.append("")
        o.append("[All joints](../joints.md) · [All parts](../parts.md) · [Front page](../index.md)")
        return "\n".join(o) + "\n"

    def parts_page(self):
        base = "../"
        o = [MARK, "# Parts", "", self.status_block(full=False), "",
             f"{self.m['cad_qty_note']} {self.m['inventory_status']}.", "",
             "| # | Picture | Part | Size, material | CAD qty | Stock | Used in |", "| ---: | --- | --- | --- | ---: | --- | --- |"]
        used = {}
        for u in self.units:
            for part, qty in self.unit_parts(u):
                used.setdefault(part["label"], []).append(f"[{u['number']}](subassemblies/{u['slug']}.md)")
        for p in self.m["inventory"]:
            pics = f'<img src="{base}manual/images/{E(p["thumbnail"])}" width="96" alt="">'
            if p.get("end_view"):
                pics += f' <img src="{base}manual/images/{E(p["end_view"])}" width="48" alt="end view">'
            details = " · ".join(x for x in (p["dimensions"], p.get("details"), p.get("description")) if x)
            note = f'<br><strong>⚠ {E(p["review_note"])}</strong>' if p.get("review_note") else ""
            stock = p.get("stock_text") or "on hand unknown"
            o.append(f'| <span id="part-{p["label"]}"></span>{p["label"]} | {pics} | {E(p["label_text"])}{note} | {E(details)} | '
                     f'{p["required"]} {E(p["unit"])} | {E(stock)} | {", ".join(used.get(p["label"], []))} |')
        o += ["", self.m["count_box_note"], "", "Print the [compact PDF](manual/" + next((n.name for n in sorted(self.manual_dir.glob('*.pdf')) if 'appendix' not in n.name), '') + ") for paper count boxes."]
        return "\n".join(o) + "\n"

    def joints_page(self):
        o = [MARK, "# Joint close-ups (inspection views)", "", self.status_block(full=False), ""]
        for j in self.m["joints"]:
            o.append(f"## Joint {j['index']}: {j['joint_id']}")
            o.append("")
            o.append(f"![Joint {j['index']}: {j['joint_id']}](manual/images/{j['image']})")
            o.append("")
            parts = ", ".join(f"{p['label']} {E(p['label_text'])} ×{p['qty']}" for p in j["parts"])
            o.append(f"{E(j['note'])}. Context: {E(j['context_text'])}. Parts: {parts}.")
            o.append("")
            if j.get("hardware"):
                o.append(f"**{E(self.m['supplement']['hardware_heading'])}**")
                o.append("")
                for h in j["hardware"]:
                    o.append(f"- **{h['label']}** {E(h['title'])}: {E(h['status_text'])}; {E(h['required_text'])} ([details](supplement.md#{slug(h['item_id'])}))")
                o.append("")
        return "\n".join(o) + "\n"

    def supplement_page(self):
        s = self.m["supplement"]
        o = [MARK, "# Supplementary items (not modelled in CAD)", "", self.status_block(full=False), "", E(s["note"]) + (f" Status: {E(s['status'])}." if s.get("status") else ""), ""]
        if not s["present"]:
            return "\n".join(o + ["No supplementary items are recorded."]) + "\n"
        o += ["| # | Item | Kind, status | Required | Stock | Included with | Config. confirmed |", "| --- | --- | --- | --- | --- | --- | --- |"]
        for r in s["rows"]:
            item = (f'<span id="{slug(r["item_id"])}"></span><strong>{E(r["title"])}</strong><br><code>{E(r["item_id"])}</code> · joint <code>{E(r["joint_id"])}</code>'
                    f'<br><small>attaches to: {E(r["attaches_text"])}</small>'
                    + (f'<br><small>{E(r["specification"])}</small>' if r.get("specification") and r["specification"] != r["title"] else "")
                    + (f'<br><small>evidence: {E(r["evidence"])}</small>' if r.get("evidence") else ""))
            scope = " (new design, appendix only)" if r.get("appendix_only") else ""
            o.append(f"| {r['label']}{scope} | {item} | {E(r['kind_text'])}<br>{E(r['status_text'])} | {E(r['required_text'])} | {E(r['stock_text'])} | "
                     f"{E(r['included_with_text']) or '—'} | {'yes' if r['intended_configuration_confirmed'] else 'no'} |")
        return "\n".join(o) + "\n"

    def record_page(self):
        r = self.m.get("receipt", {})
        src = self.source
        o = [MARK, "# Build record", "", self.status_block(), "",
             f"Manual `{self.m['id']}` generated {self.m['generated_at_utc']} by {E(str(r.get('generator', 'mechanical-docs')))}.", ""]
        sc = self.m["scene"]["source"]
        o += ["## Source", "", f"- Vault root `{E(sc.get('root_vault_path', ''))}`, file-version {sc.get('root_version_id')}, master {sc.get('root_master_id')}, vault {sc.get('vault_id')}.",
              f"- Exporter: {E(sc.get('exporter', ''))}.", f"- Qualification: {E(sc.get('qualification', ''))}.",
              f"- Occurrence ids: {E(sc.get('occurrence_id_scope', ''))}.", ""]
        if src:
            o += ["## Publication", "", f"- Published {src.get('published_at')} from evidence run `{src.get('evidence_run')}`.",
                  f"- Check report: all passed = {src.get('check_report', {}).get('all_passed')}, PDF pages {src.get('check_report', {}).get('pdf_pages')}."]
            for name, h in (src.get("pdf_sha256") or {}).items():
                o.append(f"- `{name}` sha256 `{h}`")
            o += ["- [SOURCE.json](manual/SOURCE.json) · [build-receipt.json](manual/build-receipt.json) · [check-report.json](manual/check-report.json) · [single-page manual](manual/index.html)", ""]
        f = self.m.get("findings", {})
        if f.get("coincident_occurrences"):
            o += ["## Findings", ""]
            for c in f["coincident_occurrences"]:
                o.append(f"- Coincident occurrences of `{E(c['part_id'])}`: {', '.join(f'`{x}`' for x in c['occurrences'])} (max deviation {c['max_deviation']:.2e} mm). The CAD cannot say which one is intended.")
            o.append("")
        o += ["## How it is built", "", "See [assembly/documentation-workflow.md](../assembly/documentation-workflow.md); the pages of this site are generated from the manual package by `assembly/site_pages.py`."]
        return "\n".join(o) + "\n"

    def write_all(self):
        written = []
        sub = DOCS / "subassemblies"
        sub.mkdir(exist_ok=True)
        for old in sub.glob("*.md"):
            if MARK in old.read_text(encoding="utf-8"):
                old.unlink()
        pages = {DOCS / "index.md": self.index_page(), DOCS / "parts.md": self.parts_page(), DOCS / "joints.md": self.joints_page(),
                 DOCS / "supplement.md": self.supplement_page(), DOCS / "record.md": self.record_page()}
        for u in self.units:
            pages[sub / f"{u['slug']}.md"] = self.unit_page(u)
        for path, text in pages.items():
            if path.exists() and MARK not in path.read_text(encoding="utf-8") and path.name != "index.md":
                raise SystemExit(f"{path} is not a generated page; refusing to overwrite")
            path.write_text(text, encoding="utf-8")
            written.append(path.relative_to(ROOT))
        return written, [(u["number"], u["definition"], u["count"], u["slug"]) for u in self.units]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--manual", type=Path, default=MANUAL)
    ap.add_argument("--scene", type=Path, default=SCENE)
    a = ap.parse_args(argv)
    site = Site(a.manual, a.scene)
    written, units = site.write_all()
    for n, d, c, s in units:
        print(f"{n:>2}  {d:<28} {c:>2} in project  subassemblies/{s}.md")
    print(f"{len(written)} pages written; viewer {'present' if site.viewer_block() else 'absent (static callouts only)'}")


if __name__ == "__main__":
    main()
